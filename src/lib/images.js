// Screenshot checks by their first bytes (docs/SDD.md, "Feedback and
// screenshots"): PNG 89 50 4E 47, JPEG FF D8 FF, WebP "RIFF....WEBP".
// The file name and the browser's Content-Type are ignored.

/** The image type from its first bytes, or null. */
export function sniffImage(bytes) {
  const b = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);
  if (b.length >= 8 && b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4e && b[3] === 0x47 && b[4] === 0x0d && b[5] === 0x0a && b[6] === 0x1a && b[7] === 0x0a) return "image/png";
  if (b.length >= 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return "image/jpeg";
  if (b.length >= 12 && b[0] === 0x52 && b[1] === 0x49 && b[2] === 0x46 && b[3] === 0x46 && b[8] === 0x57 && b[9] === 0x45 && b[10] === 0x42 && b[11] === 0x50) return "image/webp";
  return null;
}

export const EXT = { "image/png": "png", "image/jpeg": "jpg", "image/webp": "webp" };
